import "@/public/globals.css";
import CustomLayout from "@/components/CustomLayout";
import { Unbounded } from 'next/font/google';

const unbounded = Unbounded({
  subsets: ['latin'],
  variable: '--font-unbounded',
  weight: ['400', '500', '600', '700', '800', '900'],
  display: 'swap',
});

import prisma from "@/lib/prisma";

export async function generateMetadata() {
  const seoSettings = await prisma.sEOSettings.findFirst();
  const generalSettings = await prisma.generalSettings.findFirst();

  return {
    title: {
      default: seoSettings?.metaTitle || "Karınca",
      template: `%s | ${seoSettings?.metaTitle || "Karınca"}`
    },
    description: seoSettings?.metaDescription || "Generated by create next app",
    keywords: seoSettings?.metaKeywords ? seoSettings.metaKeywords.split(',') : [],
    icons: {
      icon: generalSettings?.faviconUrl || '/favicon.ico',
      shortcut: generalSettings?.faviconUrl || '/favicon.ico',
      apple: generalSettings?.faviconUrl || '/favicon.ico',
    },
    openGraph: {
      title: seoSettings?.metaTitle || "Karınca",
      description: seoSettings?.metaDescription,
      images: seoSettings?.ogImage ? [{ url: seoSettings.ogImage }] : [],
      type: 'website',
    },
    twitter: {
      card: 'summary_large_image',
      title: seoSettings?.metaTitle || "Karınca",
      description: seoSettings?.metaDescription,
      images: seoSettings?.ogImage ? [seoSettings.ogImage] : [],
      creator: seoSettings?.twitterHandle,
    }
  };
}

export default function RootLayout({ children }) {
  return (
    <html lang="tr" suppressHydrationWarning className={unbounded.variable}>
      <body className={`${unbounded.className} antialiased`} suppressContentEditableWarning suppressHydrationWarning>
        <CustomLayout>
          {children}
        </CustomLayout>
      </body>
    </html>
  );
}
